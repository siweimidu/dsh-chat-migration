#!/usr/bin/env node
/**
 * Measures, per published Harness version, whether the extension points our plugins
 * rely on actually exist. Produces docs/COMPATIBILITY.md — measured, not asserted.
 */

import { execFileSync } from 'node:child_process'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { createWriteStream } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { Readable } from 'node:stream'
import { pipeline } from 'node:stream/promises'
import { fileURLToPath } from 'node:url'

const VERSIONS = ['0.1.7-rc.2', '0.2.0-rc.2', '0.2.1-rc.2', '0.2.2-rc.3']

/** Packages whose bundles render the slots our plugins register into. */
const SLOT_PROBES = [
  { pkg: 'dsh-client-ui-settings-general', slots: ['settings.section'] },
  { pkg: 'dsh-client-ui-conversation', slots: ['conversation.session.header.utilities'] },
]

/** Host packages the shipped plugins import at runtime. */
const REQUIRED_PACKAGES = [
  'dsh-session-log-export',
  'dsh-session',
  'dsh-llm',
  'dsh-commands',
  'dsh-attachment',
  'dsh-agent-preset-registry',
  'dsh-client-ui-settings',
  'dsh-client-ui-conversation',
]

const REGISTRY = 'https://registry.npmjs.org/'
const proxy = process.env.HTTPS_PROXY || process.env.HTTP_PROXY
const fetchImpl = proxy ? await proxyFetch(proxy) : fetch

async function proxyFetch(proxyUrl) {
  const { ProxyAgent, fetch: undiciFetch } = await import('undici').catch(() => ({}))
  if (!ProxyAgent) return fetch
  const dispatcher = new ProxyAgent(proxyUrl)
  return (input, init = {}) => undiciFetch(input, { ...init, dispatcher })
}

async function packument(pkg) {
  const response = await fetchImpl(`${REGISTRY}${encodeURIComponent(`@deepseek-ai/${pkg}`)}`)
  if (!response.ok) throw new Error(`${pkg}: registry ${response.status}`)
  return response.json()
}

async function downloadTarball(url, destination) {
  const response = await fetchImpl(url)
  if (!response.ok) throw new Error(`${url}: ${response.status}`)
  await pipeline(Readable.fromWeb(response.body), createWriteStream(destination))
}

const results = []
const workdir = await mkdtemp(join(tmpdir(), 'dsh-compat-'))

try {
  const packuments = new Map()
  for (const pkg of new Set([...SLOT_PROBES.map(probe => probe.pkg), ...REQUIRED_PACKAGES])) {
    packuments.set(pkg, await packument(pkg))
  }

  for (const version of VERSIONS) {
    const row = { version, slots: {}, packages: {} }

    for (const { pkg, slots } of SLOT_PROBES) {
      const meta = packuments.get(pkg)
      if (meta.versions[version] === undefined) {
        for (const slot of slots) row.slots[slot] = 'n/a'
        continue
      }
      const dir = join(workdir, `${pkg}-${version}`)
      await mkdir(dir, { recursive: true })
      const tarball = join(workdir, `${pkg}-${version}.tgz`)
      await downloadTarball(meta.versions[version].dist.tarball, tarball)
      execFileSync('tar', ['-xzf', tarball, '-C', dir], { stdio: 'ignore' })
      let bundle = ''
      try {
        bundle = await readFile(join(dir, 'package', 'lib', 'client.js'), 'utf8')
      } catch {
        bundle = ''
      }
      for (const slot of slots) {
        // Published bundles differ in quoting and minification, so match any quote style.
        const rendered = new RegExp(`renderSlot\\(\\s*['"\`]${slot.replaceAll('.', '\\.')}['"\`]`).test(bundle)
        const mentioned = bundle.includes(slot)
        row.slots[slot] = rendered ? 'yes' : mentioned ? 'mentioned' : 'no'
      }
    }

    for (const pkg of REQUIRED_PACKAGES) {
      row.packages[pkg] = packuments.get(pkg).versions[version] === undefined ? 'no' : 'yes'
    }

    results.push(row)
    console.log(`measured ${version}`)
  }
} finally {
  await rm(workdir, { recursive: true, force: true })
}

const slotColumns = SLOT_PROBES.flatMap(probe => probe.slots)
const lines = [
  '# Measured host compatibility',
  '',
  'Generated by `pnpm compat:matrix` from the published npm packages — every cell is read out of the',
  'shipped `lib/client.js` bundles (slots) or the registry metadata (packages), not assumed.',
  '',
  '## Slots our plugins register into',
  '',
  `| Host version | ${slotColumns.map(slot => `\`${slot}\``).join(' | ')} |`,
  `| --- | ${slotColumns.map(() => '---').join(' | ')} |`,
  ...results.map(row => `| ${row.version} | ${slotColumns.map(slot => row.slots[slot]).join(' | ')} |`),
  '',
  '## Host packages our plugins import',
  '',
  `| Host version | ${REQUIRED_PACKAGES.map(pkg => `\`${pkg}\``).join(' | ')} |`,
  `| --- | ${REQUIRED_PACKAGES.map(() => '---').join(' | ')} |`,
  ...results.map(row => `| ${row.version} | ${REQUIRED_PACKAGES.map(pkg => row.packages[pkg]).join(' | ')} |`),
  '',
]

const output = fileURLToPath(new URL('../docs/COMPATIBILITY.md', import.meta.url))
await writeFile(output, `${lines.join('\n')}\n`)
console.log(`wrote ${output}`)
